def tr(language: str, key: str, **values) -> str:
    """Tra cứu nghiêm ngặt: thiếu bản dịch sẽ báo lỗi để phát hiện khi kiểm thử."""
    return TEXT[language][key].format(**values)


def experience_text(language: str, years: float, *, badge: bool = False) -> str:
    """Một nguồn định dạng chung cho bộ lọc và thẻ, có số ít/số nhiều tiếng Anh."""
    return tr(language, "experience_badge" if badge else "years",
              count=f"{years:g}", unit="year" if years == 1 else "years")
